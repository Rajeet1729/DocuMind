/**
 * Slice-2 answer evaluation harness — <b>Step 2: faithfulness + abstention</b>.
 *
 * <p>Builds on the Step-1 retrieval harness by scoring the <em>generated answer</em>.
 * For each answerable entry it runs the real pipeline ({@link AskQuestionUseCase#ask})
 * and asks an LLM judge ({@code gpt-6-luna}) whether the answer is faithful to — grounded
 * in — the retrieved context. For each should-return-nothing entry it asks the judge
 * whether the pipeline correctly abstained. These are the first <b>paid chat</b> calls
 * the project makes (generation + judge), on top of the embedding calls from Step 1.
 *
 * <p>Key decisions, carried from the approved design and the Step-2 brief:
 * <ul>
 *   <li><b>Faithfulness headline = share SUPPORTED.</b> PARTIAL is reported separately as
 *       not-fully-faithful; UNSUPPORTED and any unparseable judge replies are shown too.
 *       Faithfulness is answer-vs-context grounding, independent of the golden
 *       {@code expectedAnswer} (which is for correctness, a different metric).</li>
 *   <li><b>The judge sees the FULL retrieved chunk text</b>, not the truncated citation
 *       snippets — so the harness re-derives the retrieved chunks with its own
 *       {@code search()} (deterministic: same query, same index as the pipeline's
 *       internal retrieval) and hands the judge a numbered context block of full text.</li>
 *   <li><b>Abstention is its own metric</b>, kept out of the faithfulness headline.</li>
 *   <li><b>Cost:</b> judge tokens are measured from the API; embedding and generation
 *       tokens are jtokkit estimates (see {@link CostModel}). Per question the harness
 *       issues two query embeddings — its own {@code search()} plus the one inside
 *       {@code ask()} — the "one redundant query-embedding" the S1 decision allowed.</li>
 * </ul>
 *
 * <p>Same build wiring as {@code RetrievalEvaluation}: {@code *Evaluation} name and
 * {@code @Tag("eval")} keep it out of {@code mvn test}; run with {@code ./mvnw test -Peval}.
 */
@Tag("eval")
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
@SpringBootTest(properties = "spring.docker.compose.enabled=false")
@Import(TestcontainersConfiguration.class)
class FaithfulnessEvaluation {

	private static final int RATIONALE_WIDTH = 110;

	@Autowired
	private DocumentChunker chunker;

	@Autowired
	private ChunkStore chunkStore;

	@Autowired
	private AskQuestionUseCase askQuestion;

	@Autowired
	private ChatClient.Builder chatClientBuilder;

	@Value("${documind.retrieval.top-k:4}")
	private int topK;

	@Value("${spring.ai.openai.chat.model:unknown}")
	private String generationModel;

	/**
	 * Judge model, overridable so swapping judges is a one-line change, not a code edit:
	 * {@code ./mvnw test -Peval -Ddocumind.eval.judge-model=gpt-6-sol}. Only the judge
	 * changes — answers are always generated by the app's configured model. Defaults to
	 * the self-judge ({@code gpt-6-luna}).
	 */
	@Value("${documind.eval.judge-model:gpt-6-luna}")
	private String judgeModel;

	private List<GoldenEntry> golden;
	private final List<String> ingestedFiles = new ArrayList<>();
	private CostModel cost;

	@BeforeAll
	void ingestCorpusOnce() {
		golden = GoldenSet.load();
		cost = new CostModel(judgeModel);

		// Ingest each distinct source file ONCE (embeds the corpus a single time), inlining
		// the chunk -> save so we can also tally the corpus embedding tokens for the cost
		// summary. Mirrors RetrievalEvaluation's ingestion.
		golden.stream().map(GoldenEntry::filename).distinct().forEach(filename -> {
			ClassPathResource pdf = new ClassPathResource("eval/corpus/" + filename);
			if (!pdf.exists()) {
				return; // flagged/skipped later; e.g. the résumé is intentionally not committed
			}
			byte[] bytes;
			try {
				bytes = pdf.getContentAsByteArray();
			}
			catch (IOException e) {
				throw new IllegalStateException("could not read corpus file " + filename, e);
			}
			List<Chunk> chunks = chunker.chunk(UUID.randomUUID().toString(), filename, bytes);
			chunkStore.save(chunks);
			ingestedFiles.add(filename);
			chunks.forEach(c -> cost.addCorpusEmbedding(c.text()));
		});

		assertThat(ingestedFiles).as("at least the public Huberman corpus must ingest")
				.contains("huberman_sleep.pdf");
	}

	@Test
	void answerFaithfulnessAndAbstention() {
		Judge judge = new Judge(chatClientBuilder, judgeModel);
		RunReport report = new RunReport();

		printHeader(judge);
		printJudgePrompts();
		printTableHead();

		for (GoldenEntry e : golden) {
			if (!ingestedFiles.contains(e.filename())) {
				printLine(e.id(), e.type(), "SKIP", "source file '" + e.filename() + "' not ingested");
				report.add(new RunReport.QResult(e.id(), e.type(), e.question(), "",
						List.of(), null, null, e.relevantPages(), "SKIP",
						"source file '" + e.filename() + "' not ingested", e.isShouldReturnNothing()));
				continue;
			}

			// Re-derive the retrieved chunks the pipeline will use (full text for the judge),
			// then run the real pipeline for the answer. Two query embeddings per question.
			List<RetrievedChunk> retrieved = chunkStore.search(e.question(), topK);
			cost.addQueryEmbedding(e.question()); // this harness search()
			Answer answer = askQuestion.ask(e.question());
			cost.addQueryEmbedding(e.question()); // the search() inside ask()

			String context = numberedContext(retrieved);
			cost.addGeneration(cost.chatTokens(context) + cost.chatTokens(e.question()), answer.text());
			List<RunReport.Retrieved> ranked = toRanked(retrieved);

			if (e.isShouldReturnNothing()) {
				AbstentionJudgement j = judge.judgeAbstention(e.question(), answer.text());
				cost.addJudge(j.promptTokens(), j.completionTokens());
				String verdict = !j.parsed() ? "UNPARSEABLE"
						: j.abstained() ? "ABSTAIN-OK" : "FAIL-answered";
				printLine(e.id(), e.type(), verdict, j.rationale());
				report.add(new RunReport.QResult(e.id(), e.type(), e.question(), answer.text(),
						ranked, null, null, e.relevantPages(), verdict, j.rationale(), true));
			}
			else {
				boolean hit1 = !retrieved.isEmpty()
						&& e.isHit(retrieved.get(0).chunk().provenance().filename(),
								retrieved.get(0).chunk().provenance().pageNumber());
				boolean hitK = retrieved.stream().anyMatch(rc -> e.isHit(
						rc.chunk().provenance().filename(), rc.chunk().provenance().pageNumber()));
				FaithfulnessJudgement j = judge.judgeFaithfulness(e.question(), context, answer.text());
				cost.addJudge(j.promptTokens(), j.completionTokens());
				printLine(e.id(), e.type(), j.grade().name(), j.rationale());
				report.add(new RunReport.QResult(e.id(), e.type(), e.question(), answer.text(),
						ranked, hit1, hitK, e.relevantPages(), j.grade().name(), j.rationale(), false));
			}
		}

		// Console summary (derived from the collected results) + cost.
		System.out.println("------------------------------------------------------------------");
		report.summaryLines().forEach(System.out::println);
		cost.printSummary();

		// Persist a timestamped, diff-friendly report under target/eval/.
		String stamp = DateTimeFormatter.ofPattern("yyyyMMdd'T'HHmmss'Z'")
				.withZone(ZoneOffset.UTC).format(Instant.now());
		Path file = Path.of("target", "eval", "results-" + stamp + ".txt");
		report.write(file, runMetaLines(judge, stamp), cost.summaryLines());
		System.out.println("------------------------------------------------------------------");
		System.out.println(" persisted results: " + file.toAbsolutePath());
		System.out.println("==================================================================");
	}

	private List<String> runMetaLines(Judge judge, String stamp) {
		return List.of(
				"timestamp=" + stamp,
				"generationModel=" + generationModel + "  judgeModel=" + judge.judgeModel(),
				"topK=" + topK + "  entries=" + golden.size() + "  ingested=" + ingestedFiles);
	}

	private static List<RunReport.Retrieved> toRanked(List<RetrievedChunk> retrieved) {
		return retrieved.stream()
				.map(rc -> new RunReport.Retrieved(rc.chunk().provenance().filename(),
						rc.chunk().provenance().pageNumber(), rc.score()))
				.toList();
	}

	/** Numbered, 1-based context block of FULL chunk text — the judge's view of retrieval. */
	private static String numberedContext(List<RetrievedChunk> chunks) {
		StringBuilder sb = new StringBuilder();
		for (int i = 0; i < chunks.size(); i++) {
			if (i > 0) {
				sb.append("\n\n");
			}
			sb.append('[').append(i + 1).append("] ").append(chunks.get(i).chunk().text());
		}
		return sb.toString();
	}

	// --- printing -----------------------------------------------------------------

	private void printHeader(Judge judge) {
		System.out.println();
		System.out.println("==================================================================");
		System.out.println(" DocuMind answer eval — faithfulness + abstention (Step 2, PAID)");
		System.out.println(" entries = " + golden.size() + "   top-k = " + topK
				+ "   ingested = " + ingestedFiles);
		System.out.println(" generation model = " + generationModel
				+ "   judge model = " + judge.judgeModel());
		System.out.println("==================================================================");
	}

	private void printJudgePrompts() {
		System.out.println(" JUDGE SYSTEM PROMPT — faithfulness (logged verbatim):");
		System.out.println(indent(Judge.FAITHFULNESS_SYSTEM_PROMPT));
		System.out.println();
		System.out.println(" JUDGE SYSTEM PROMPT — abstention (logged verbatim):");
		System.out.println(indent(Judge.ABSTENTION_SYSTEM_PROMPT));
		System.out.println("------------------------------------------------------------------");
	}

	private void printTableHead() {
		System.out.printf(" %-5s %-13s %-13s %s%n", "id", "type", "verdict", "judge rationale");
	}

	private void printLine(String id, String type, String verdict, String rationale) {
		System.out.printf(" %-5s %-13s %-13s %s%n", id, type, verdict, truncate(rationale));
	}

	private static String truncate(String text) {
		String t = text == null ? "" : text.replaceAll("\\s+", " ").strip();
		return t.length() <= RATIONALE_WIDTH ? t : t.substring(0, RATIONALE_WIDTH - 1) + "…";
	}

	private static String indent(String block) {
		return "   | " + block.replace("\n", "\n   | ");
	}
}
